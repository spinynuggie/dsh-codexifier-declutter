// Bundles src/appearance into client.js between the appearance-engine markers.
// Run with: node scripts/build-appearance.mjs (needs node and network access for npx esbuild)
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const root = fileURLToPath(new URL('..', import.meta.url))
const bundle = execFileSync('npx', [
  '-y', 'esbuild@0.28',
  'src/appearance/entry.ts',
  '--bundle', '--format=iife', '--global-name=__dshAppearance', '--target=chrome120',
  '--loader:.frag=text', '--minify-syntax', '--legal-comments=none',
], { cwd: root, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })

const START = '    // <appearance-engine> generated by scripts/build-appearance.mjs, do not edit by hand'
const END = '    // </appearance-engine>'
const file = new URL('../client.js', import.meta.url)
const source = await readFile(file, 'utf8')
const from = source.indexOf(START)
const to = source.indexOf(END)
if (from < 0 || to < from) throw new Error('appearance-engine markers not found in client.js')

const block = `${START}\n    const AppearanceEngine = (() => {\n${bundle.trim()}\n      return __dshAppearance\n    })()\n`
await writeFile(file, source.slice(0, from) + block + source.slice(to))
console.log(`appearance engine: ${bundle.length} bytes`)
